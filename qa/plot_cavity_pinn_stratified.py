def require(condition, message):
    if not condition:
        raise ValueError(message)


def load_completed(path):
    """Re-run the read-only completed-comparison checks before reading fields."""
    path = Path(path).resolve()
    require(path.is_file(), 'The completed 12-pair comparison manifest is unavailable. No figures were generated.')
    require(path.is_relative_to(ROOT.resolve()), 'Comparison must be inside the checkout')
    digest = retained.sha(path)
    manifest = comparison.read_json(path)
    require(manifest['schema_version'] == 1 and manifest['campaign_kind'] ==
            'ghia_uniform_vs_stratified_matched_work', 'Wrong comparison schema')
    require(manifest['comparison_source_sha256'] == retained.sha(comparison.__file__),
            'Completed comparison was generated by a different comparator source')
    inputs = {name: comparison.checked_entry(ROOT, item) for name, item in manifest['inputs'].items()}
    # An existing comparison invokes the comparator's validation-only return;
    # it never rewrites scores or selects/trains a model.
    checked = comparison.execute(inputs['baseline_manifest'], inputs['variant_raw_manifest'],
                                 inputs['experiment_manifest'], path.parent, root=ROOT)
    require(checked == manifest and retained.sha(path) == digest, 'Completed comparison changed during verification')
    baseline = comparison.read_json(inputs['baseline_manifest'])
    variant = comparison.read_json(inputs['variant_raw_manifest'])
    b = comparison.indexed(baseline['records'], comparison.BASE_EXPECTED)
    v = comparison.indexed(variant['records'], comparison.EXPECTED)
    pairs = comparison.indexed(manifest['records'], comparison.EXPECTED, require_scored=False)
    for key, pair in pairs.items():
        require(pair['baseline_run_id'] == b[key]['run_id'] and pair['stratified_run_id'] == v[key]['run_id'],
                'Comparison counterpart does not match the score manifest')
        for label, row in [('baseline', b[key]), ('stratified', v[key])]:
            require(pair[label+'_prediction'] == row['prediction'] and pair[label+'_profiles'] == row['ghia_profiles'],
                    'Comparison prediction/profile identity differs from the scored freeze')
        require(pair['closure_cap'] > 0 and pair['matched_residual_point_evaluations'] > 0,
                'Invalid paired work count')
    paths = {name: comparison.checked_entry(ROOT, item) for name, item in manifest['outputs'].items()}
    with paths['paired_signed_profiles'].open(encoding='utf-8-sig', newline='') as stream:
        profiles = list(csv.DictReader(stream))
    with paths['paired_metrics'].open(encoding='utf-8-sig', newline='') as stream:
        metrics = list(csv.DictReader(stream))
    return manifest, pairs, b, v, profiles, metrics


def native_triplet(baseline, stratified):
    uniform, ref = retained.arrays(baseline)
    proposed, ref2 = retained.arrays(stratified)
    require(ref['u'].shape == (511, 511), 'Expected the verified 511 by 511 native interior')
    for key in ('x', 'y', 'u', 'v', 'psi', 'omega'):
        require(np.array_equal(ref[key], ref2[key]), 'The two methods do not share exactly the same CFD reference')
    for field in (uniform, proposed):
        require(np.array_equal(field['x'], ref['x']) and np.array_equal(field['y'], ref['y']),
                'Different physical native grids cannot be overlaid')
    return ref, uniform, proposed


def profile_cache(baseline, stratified, profile_rows):
    """Retain only small one-dimensional slices, not all 24 large fields."""
    result = {}
    for key in sorted(comparison.EXPECTED):
        fields = native_triplet(baseline[key], stratified[key])
        reference = fields[0]
        ix = int(np.argmin(abs(reference['x']-.5)))
        iy = int(np.argmin(abs(reference['y']-.5)))
        require(reference['x'][ix] == .5 and reference['y'][iy] == .5, 'Missing exact native centreline')
        item = {'x': reference['x'].copy(), 'y': reference['y'].copy(),
                'u': [f['u'][:, ix].copy() for f in fields],
                'v': [f['v'][iy].copy() for f in fields], 'samples': {}}
        rows = [r for r in profile_rows if (int(r['Re']), int(r['seed']), float(r['collar'])) == key]
        for component in ('u', 'v'):
            selected = sorted((r for r in rows if r['component'] == component), key=lambda r: float(r['position']))
            require(len(selected) == 17, 'Expected all 17 published Ghia positions, including flagged entries')
            sample = {name: np.array([float(r[name]) for r in selected]) for name in
                      ('position', 'published', 'baseline_prediction', 'stratified_prediction',
                       'baseline_signed_error_U', 'stratified_signed_error_U')}
            sample['included'] = np.array([r['screened_included'].lower() == 'true' for r in selected])
            require(np.all(np.diff(sample['position']) > 0), 'Duplicate or unordered profile positions')
            for method in ('baseline', 'stratified'):
                require(np.allclose(sample[method+'_prediction']-sample['published'],
                                    sample[method+'_signed_error_U'], rtol=1e-12, atol=1e-14),
                        'Signed profile error is inconsistent')
            item['samples'][component] = sample
        result[key] = item
    return result


def padded_limits(values, fraction=.055):
    lo, hi = float(np.min(values)), float(np.max(values))
    pad = fraction*max(hi-lo, 1e-8)
    return lo-pad, hi+pad


def profile_limits(cache, re):
    rows = [cache[key] for key in sorted(cache) if key[0] == re]
    limits = {}
    for component in ('u', 'v'):
        values = np.concatenate([np.concatenate(row[component]+[row['samples'][component]['published']]) for row in rows])
        errors = np.concatenate([np.r_[row['samples'][component]['baseline_signed_error_U'],
                                       row['samples'][component]['stratified_signed_error_U']] for row in rows])
        limits[component] = padded_limits(values)
        extent = max(float(abs(errors).max())*1.08, 1e-12)
        limits[component+'_error'] = (-extent, extent)
    return limits


def profile_figure(re, collar, cache, limits):
    fig, axes = plt.subplots(2, 2, figsize=(9.2, 8.1))
    fig.subplots_adjust(left=.1, right=.97, top=.89, bottom=.28, wspace=.31, hspace=.34)
    fig.suptitle(fr'Re = {re}; $\epsilon={collar:g}$: signed profiles and Ghia errors'+'\n'
                 'Uniform versus area-weighted stratified collocation', fontsize=13, y=.985)
    for index, seed in enumerate(SEEDS):
        item = cache[(re, seed, collar)]
        for column, component in enumerate(('u', 'v')):
            sample = item['samples'][component]
            if index == 0:
                if component == 'u':
                    axes[0, column].plot(item['u'][0], item['y'], color='black', lw=1.9, zorder=2)
                else:
                    axes[0, column].plot(item['x'], item['v'][0], color='black', lw=1.9, zorder=2)
                included = sample['included']
                xy = (sample['published'], sample['position']) if component == 'u' else (sample['position'], sample['published'])
                axes[0, column].scatter(xy[0][included], xy[1][included], s=31, facecolors='white', edgecolors='black', zorder=7)
                axes[0, column].scatter(xy[0][~included], xy[1][~included], s=43, color='#B2182B', marker='x', zorder=8)
            for method, number, style in [('baseline', 1, '--'), ('stratified', 2, '-')]:
                if component == 'u':
                    axes[0, column].plot(item['u'][number], item['y'], color=COLORS[seed], ls=style, lw=1.15)
                else:
                    axes[0, column].plot(item['x'], item['v'][number], color=COLORS[seed], ls=style, lw=1.15)
                errors = sample[method+'_signed_error_U']
                # Markers show every actual printed position; no extrapolation or resampling.
                axes[1, column].plot(sample['position'], errors, color=COLORS[seed], ls=style, marker='o', ms=2.6, lw=1)
                axes[1, column].scatter(sample['position'][~sample['included']], errors[~sample['included']],
                                        color='#B2182B', marker='x', s=30, zorder=8)
    axes[0, 0].set(xlabel=r'$u/U$ at $x/W=0.5$', ylabel=r'$y/W$', xlim=limits['u'], ylim=(0, 1))
    axes[0, 1].set(xlabel=r'$x/W$', ylabel=r'$v/U$ at $y/W=0.5$', xlim=(0, 1), ylim=limits['v'])
    for column, component in enumerate(('u', 'v')):
        axes[1, column].axhline(0, color='.4', lw=.8, zorder=1)
        axes[1, column].set(xlabel=r'$y/W$' if component == 'u' else r'$x/W$',
                           ylabel=f'Signed {component} error / U', xlim=(0, 1), ylim=limits[component+'_error'])
    for ax in axes.flat:
        ax.grid(alpha=.18); ax.tick_params(labelsize=10)
    handles = [Line2D([], [], color='black', lw=1.7, label='Retained CFD'),
               Line2D([], [], color='black', marker='o', mfc='white', ls='none', label='Ghia printed samples'),
               Line2D([], [], color='.3', ls='--', label='Uniform PINN'),
               Line2D([], [], color='.3', ls='-', label='Stratified PINN'),
               *[Line2D([], [], color=COLORS[s], label=f'Seed {s}') for s in SEEDS],
               Line2D([], [], color='#B2182B', marker='x', ls='none', label='Flagged printed entry')]
    fig.legend(handles=handles, loc='lower center', bbox_to_anchor=(.5, .105), ncol=4, frameon=False, fontsize=10)
    fig.text(.5, .035, 'Matched closure and residual-point work within each baseline/stratified pair; caps can differ across pairs.\n'
             'Dense curves use native nodes; error markers use direct frozen predictions at printed positions.\n'
             'Both collars share these axis limits for this Re. Flagged entries remain visible.', ha='center', fontsize=9)
    return fig


def physical_scales(selected):
    speed = max(float(np.hypot(f['u'], f['v']).max()) for triple in selected.values() for f in triple)
    curl = max(float(abs(retained.centered_curl(f)).max()) for triple in selected.values() for f in triple)
    errors = {component: max(float(abs(f[component]-triple[0][component]).max())
                            for triple in selected.values() for f in triple[1:]) for component in ('u', 'v')}
    errors['curl'] = max(float(abs(retained.centered_curl(f)-retained.centered_curl(triple[0])).max())
                         for triple in selected.values() for f in triple[1:])
    values = dict(speed_vmax=speed, curl_absmax=curl, curl_symlog_linthresh=.25,
                  signed_error_absmax=errors)
    norms = {'speed': Normalize(0, max(speed, 1e-12)),
             'curl': SymLogNorm(.25, vmin=-max(curl, .25), vmax=max(curl, .25)),
             **{key+'_error': TwoSlopeNorm(0, -max(value, 1e-12), max(value, 1e-12))
                for key, value in errors.items()}}
    return values, norms


def paired_field_figure(variable, selected, norms):
    fig, axes = plt.subplots(2, 3, figsize=(11.2, 8.5))
    fig.subplots_adjust(left=.075, right=.87, top=.9, bottom=.14, wspace=.24, hspace=.24)
    for row, re in enumerate(REYNOLDS):
        for column, field in enumerate(selected[re]):
            ax = axes[row, column]
            if variable == 'speed':
                values = np.hypot(field['u'], field['v']); x, y = field['x'], field['y']; cmap = 'turbo'
            else:
                values = retained.centered_curl(field); x, y = field['x'][1:-1], field['y'][1:-1]; cmap = 'RdBu_r'
            artist = ax.pcolormesh(x, y, values, shading='nearest', cmap=cmap, norm=norms[variable], rasterized=True)
            ax.set(xlim=(0, 1), ylim=(0, 1), xlabel=r'$x/W$', ylabel=r'$y/W$' if column == 0 else None)
            ax.set_aspect('equal')
            if row == 0: ax.set_title(METHODS[column], fontsize=12)
        axes[row, 0].text(-.24, .5, f'Re = {re}', transform=axes[row, 0].transAxes, va='center', ha='right', rotation=90)
    fig.colorbar(artist, cax=fig.add_axes([.9, .24, .02, .55]), label=r'$|\mathbf{u}|/U$' if variable == 'speed' else r'$\omega W/U$')
    fig.suptitle('Speed: identical scales and spatial limits' if variable == 'speed' else
                 'Vorticity from the same centered curl of both velocity components', fontsize=14, y=.975)
    caption = ('Native 511 x 511 interior fields; linear color scale preserves the actual extrema.' if variable == 'speed' else
               'Common 509 x 509 centered curl; symmetric-log color scale, linear interval |omega W/U| < 0.25.\n'
               'This extra diagnostic does not replace the original PINN-AD / CFD-transported-vorticity scores.')
    fig.text(.5, .052, 'Predeclared seed 7, collar 0.02; no best-seed selection.\n'+caption, ha='center', fontsize=9)
    return fig


def signed_error_figure(re, fields, norms):
    fig, axes = plt.subplots(3, 2, figsize=(9.2, 11.6))
    fig.subplots_adjust(left=.095, right=.86, top=.92, bottom=.115, wspace=.28, hspace=.34)
    ref = fields[0]
    for row, component in enumerate(('u', 'v', 'curl')):
        for column, field in enumerate(fields[1:]):
            if component == 'curl':
                values = retained.centered_curl(field)-retained.centered_curl(ref)
                x, y = field['x'][1:-1], field['y'][1:-1]
            else:
                values = field[component]-ref[component]; x, y = field['x'], field['y']
            ax = axes[row, column]
            artist = ax.pcolormesh(x, y, values, shading='nearest', cmap='RdBu_r', norm=norms[component+'_error'], rasterized=True)
            ax.set_aspect('equal');ax.set(xlim=(0, 1), ylim=(0, 1), xlabel=r'$x/W$', ylabel=r'$y/W$')
            if row == 0:ax.set_title(METHODS[column+1], fontsize=12)
        position = axes[row, 1].get_position()
        cax = fig.add_axes([.9, position.y0, .023, position.height])
        label = r'$(\hat\omega-\omega)W/U$' if component == 'curl' else rf'$(\hat {component}-{component})/U$'
        fig.colorbar(artist, cax=cax, label=label)
    fig.suptitle(f'Re = {re}: signed field errors at seed 7, collar 0.02', fontsize=14, y=.975)
    fig.text(.5, .045, 'PINN minus retained CFD. Each row uses one linear, symmetric scale across both methods and both Re.\n'
             'The curl row applies the identical centered derivative to each retained u/v field.\n'
             'Native scientific scores are unchanged; no CFD pressure reference is available.', ha='center', fontsize=9)
    return fig


def streamline_figure(re, fields):
    extrema = np.concatenate([f['psi'].ravel() for f in fields])
    neg = max(0., -float(extrema.min()));pos = max(0., float(extrema.max()))
    levels = np.unique(np.r_[-np.geomspace(neg*1e-5, neg*.97, 15)[::-1] if neg > 1e-12 else [],
                            np.geomspace(pos*1e-5, pos*.97, 12) if pos > 1e-12 else []])
    require(len(levels) > 1, 'No finite circulation levels to plot')
    fig, axes = plt.subplots(1, 3, figsize=(12.1, 4.7), gridspec_kw={'width_ratios': [1.5, 1, 1]})
    for ax in axes:
        for field, color, style in zip(fields, ['black', '#0072B2', '#D55E00'], ['solid', '--', '-']):
            ax.contour(field['x'], field['y'], field['psi'], levels=levels, colors=color, linestyles=style, linewidths=.85)
        ax.set_aspect('equal');ax.set(xlabel=r'$x/W$', ylabel=r'$y/W$')
    for ax, bounds, title in zip(axes, [(0, 1, 0, 1), (0, .22, 0, .22), (.78, 1, 0, .22)],
                                ['Whole cavity', 'Lower left', 'Lower right']):
        ax.set(xlim=bounds[:2], ylim=bounds[2:]);ax.set_title(title, fontsize=12)
    handles = [Line2D([], [], color=c, ls=s, label=n) for c, s, n in
               zip(['black', '#0072B2', '#D55E00'], ['solid', '--', '-'], METHODS)]
    fig.legend(handles=handles, loc='lower center', bbox_to_anchor=(.5, .09), ncol=3, frameon=False)
    fig.suptitle(fr'Re = {re}; seed 7; $\epsilon=0.02$: matched streamfunction contours', fontsize=14, y=.985)
    fig.text(.5, .035, 'The same contour values are used for all three methods. Log-spaced values expose weak circulation.\n'
             'Interior native samples only; no invented wall rows or extrapolated fields.', ha='center', fontsize=9)
    fig.subplots_adjust(left=.065, right=.98, top=.82, bottom=.25, wspace=.32)
    return fig, levels


def write_narrative(path, manifest, metrics):
    lines = ['# Fixed sampling intervention: matched cavity comparison', '',
             'The intervention replaces fixed uniform collocation with conditional-uniform strata and global area weights. '
             'Each of the 12 runs keeps its own original physical/network configuration, seeded initialization and closure/point-work cap. '
             'The original 42-case failed baseline remains unchanged.', '',
             '| Re | Seed | Collar | Closures per method | Uniform vector error | Stratified vector error | Change |',
             '|---:|---:|---:|---:|---:|---:|:---|']
    by_key = {(int(r['Re']), int(r['seed']), float(r['collar'])):r for r in metrics
              if r['metric'] == 'field.interior.velocity_relative_l2'}
    require(set(by_key) == comparison.EXPECTED, 'Missing physical metric rows')
    for pair in sorted(manifest['records'], key=comparison.key_of):
        key = comparison.key_of(pair);row = by_key[key]
        lines.append(f"| {key[0]} | {key[1]} | {key[2]:g} | {pair['closure_cap']} | "
                     f"{100*float(row['baseline']):.3f}% | {100*float(row['stratified']):.3f}% | {row['outcome']} |")
    lines += ['', 'The signed centreline sheets contain all three seeds, both collars and the actual printed Ghia positions. '
              'Predeclared seed 7 / collar 0.02 supplies the physical field examples; it was not chosen by its reference error.', '',
              'Speed uses one linear scale across Re100/Re7500 and all methods. Vorticity uses the same centered curl of stored u/v '
              'on 509 x 509 nodes and one symmetric-log scale; its signed error uses a linear scale. '
              'Original native AD-versus-transported-vorticity scores are retained separately. '
              'No CFD pressure truth exists in this experiment.', '',
              'A reduction in a reported error is not full-domain convergence, universal optimizer superiority, or proof of corner integrability. '
              'The fit uses a finite punctured domain. The high-Re CFD reference has its own grid uncertainty. '
              'Three paired seeds are descriptive; report worsened observables as well as improved ones. '
              'Different collar/seed pairs can have different work caps. Optimizer-step seconds do not measure campaign wall time '
              'or controlled hardware speed, and no speed ranking is made here.', '',
              '[All seeds: signed profiles and errors](all_pairs_centerlines.pdf)  |  '
              '[Matched physical field comparisons](physical_comparison.pdf)', '',
              'Hashes, fixed scales and plotting choices are recorded in `figure_manifest.json`. '
              'The authoritative score comparison remains `../comparison/comparison_manifest.json`.']
    chronology = manifest.get('evaluation_chronology', {}).get('disclosure')
    if chronology:
        lines += ['', '## Evaluation chronology', '', chronology,
                  '', 'The repaired inference path restores exact saved samples and trained state. '
                  'Cross-host regeneration can shift a few annular coordinates in the last bits; '
                  'this repair does not establish cross-platform optimizer continuation.']
    path.write_text('\n'.join(lines)+'\n', encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--comparison', type=Path, default=DEFAULT_COMPARISON)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    require(args.output.resolve() == DEFAULT_OUTPUT.resolve(), 'This generator writes only its separate stratified figures folder')
    manifest, pairs, baseline, stratified, profiles, metrics = load_completed(args.comparison)
    source_entry = retained.entry(args.comparison)
    cache = profile_cache(baseline, stratified, profiles)
    selected = {re: native_triplet(baseline[(re, 7, .02)], stratified[(re, 7, .02)]) for re in REYNOLDS}
    scales, norms = physical_scales(selected)
    configure_matplotlib();plt.rcParams.update({'font.size': 11, 'axes.titlesize': 12})
    out = args.output;out.mkdir(parents=True, exist_ok=True);figures = []
    axis_limits = {re: profile_limits(cache, re) for re in REYNOLDS}
    with PdfPages(out/'all_pairs_centerlines.pdf') as pdf:
        for re in REYNOLDS:
            for collar in COLLARS:
                item = retained.save_rgb(profile_figure(re, collar, cache, axis_limits[re]),
                                         out/f're{re}_eps{collar:g}_centerlines.png', pdf)
                item.update(kind='signed_profiles_all_paired_seeds', Re=re, collar=collar, seeds=list(SEEDS))
                figures.append(item)
    figures.append(retained.entry(out/'all_pairs_centerlines.pdf'))
    with PdfPages(out/'physical_comparison.pdf') as pdf:
        for variable in ('speed', 'curl'):
            item = retained.save_rgb(paired_field_figure(variable, selected, norms), out/f'paired_{variable}.png', pdf)
            item.update(kind='matched_'+variable+'_fields', Re=list(REYNOLDS), seed=7, collar=.02);figures.append(item)
        for re in REYNOLDS:
            item = retained.save_rgb(signed_error_figure(re, selected[re], norms), out/f're{re}_signed_errors.png', pdf)
            item.update(kind='signed_native_and_common_curl_errors', Re=re, seed=7, collar=.02);figures.append(item)
            fig, levels = streamline_figure(re, selected[re])
            item = retained.save_rgb(fig, out/f're{re}_streamlines.png', pdf)
            item.update(kind='three_method_streamfunction_overlay', Re=re, seed=7, collar=.02, levels=levels.tolist());figures.append(item)
    figures.append(retained.entry(out/'physical_comparison.pdf'))
    write_narrative(out/'README.md', manifest, metrics)
    require(retained.entry(args.comparison) == source_entry, 'Input comparison changed while plotting')
    for item in manifest['inputs'].values():comparison.checked_entry(ROOT, item)
    record = dict(schema_version=1, campaign_kind='ghia_uniform_vs_stratified_matched_work',
                  generated_at_utc=datetime.now(timezone.utc).isoformat(), source_comparison=source_entry,
                  source_inputs=manifest['inputs'], generator=retained.entry(__file__),
                  helper_sources=[retained.entry(retained.__file__), retained.entry(comparison.__file__),
                                  retained.entry(ROOT/'qa/lecture_typography.py')], figures=figures,
                  represented_pairs=12, profile_axis_limits=axis_limits, shared_scales=scales,
                  representative_selection='Predeclared Re100/Re7500, seed7, collar0.02; no best-seed selection',
                  matched_work='Exact per-pair closure and residual-point caps; caps can differ across pairs',
                  native_grid=[511, 511], common_centered_curl_grid=[509, 509],
                  original_42_baseline_gallery='unchanged', pressure_reference='unavailable',
                  scientific_acceptance='Not inferred from completed execution or plotting. See every paired metric and physical profile.',
                  limits=manifest['limits'], evaluation_chronology=manifest.get('evaluation_chronology', {}),
                  evaluation_provenance=manifest.get('evaluation_provenance', {}), visual_review='pending readable individual-page inspection')
    (out/'figure_manifest.json').write_text(json.dumps(record, indent=2, allow_nan=False)+'\n', encoding='utf-8')
    print(json.dumps(dict(status='generated; visual review pending', verified_pairs=len(pairs), pngs=10, pdf_pages=10), indent=2))


if __name__ == '__main__':
    main()
