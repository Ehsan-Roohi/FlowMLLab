"""Validate and retain selected Week 13 Unity outputs.

The script intentionally excludes optimizer checkpoints. It normalizes claim
labels generated by the first pilot commit, but never changes numerical values.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil


CASES = ((100, 1), (400, 1), (100, 2), (400, 2))
FILES = ("audit.json", "optimizer-history.jsonl", "adam-endpoint.json",
         "fields.png", "loss.png", "environment-lock.txt")
UPSTREAM_COMMIT = "fcb1566eaa3253d4a4108fbac9d49a38fd10ad6b"
UPSTREAM_SHA256 = "391a2174cb9f6e8863c14d7b350077e54209134de9f85a17719c398146f91458"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("tmp"))
    parser.add_argument("--destination", type=Path,
                        default=Path("results/week13_rectangular_pinn"))
    args = parser.parse_args()
    args.destination.mkdir(parents=True, exist_ok=True)
    manifest = {"schema": 1, "cases": {}}
    for reynolds, depth in CASES:
        source = args.source / f"week13-pinn-re{reynolds}-d{depth}"
        missing = [name for name in FILES if not (source / name).is_file()]
        if missing:
            raise FileNotFoundError(f"{source}: missing {missing}")
        audit = json.loads((source / "audit.json").read_text(encoding="utf-8"))
        if audit.get("reynolds_number") != reynolds:
            raise ValueError(f"{source}: wrong Reynolds number")
        if audit.get("aspect_ratio_depth_over_width") != depth:
            raise ValueError(f"{source}: wrong aspect ratio")
        if audit.get("upstream_commit") != UPSTREAM_COMMIT:
            raise ValueError(f"{source}: wrong upstream commit")
        if audit.get("upstream_sha256") != UPSTREAM_SHA256:
            raise ValueError(f"{source}: wrong upstream digest")
        if audit.get("precision") != "torch.float64" or "A100" not in audit.get("gpu", ""):
            raise ValueError(f"{source}: run is not the required A100 float64 evidence")
        comparison = audit.get("cfd_comparison")
        if depth == 1 and comparison is None:
            raise ValueError(f"{source}: square case lacks CFD comparison")
        if depth == 1:
            audit["claim_status"] = ("field-qualified-square-case" if comparison["all_pass"]
                                     else "field-comparison-failed-square-case")
        else:
            if comparison is not None:
                raise ValueError(f"{source}: unmatched deep case cannot use CFD field gates")
            audit["claim_status"] = "residual-audited-no-field-reference"
        target = args.destination / f"re{reynolds}-d{depth}"
        target.mkdir(parents=True, exist_ok=True)
        for name in FILES:
            if name == "audit.json":
                (target / name).write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
            else:
                shutil.copy2(source / name, target / name)
        manifest["cases"][f"re{reynolds}-d{depth}"] = {
            "slurm_job_id": audit.get("slurm_job_id"),
            "claim_status": audit["claim_status"],
            "files": {name: digest(target / name) for name in FILES},
        }
    (args.destination / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
