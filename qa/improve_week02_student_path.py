NEURON_MD=r'''### Experiment: learning rate for the neuron you just calculated

Use the same sample, target and initial parameters from Section 1. Pack the weights and bias into $\theta=(w_1,w_2,b)$ and the inputs into $\widetilde x=(x_1,x_2,1)$; the final 1 represents the bias input. With $o=\theta\cdot\widetilde x$,

$$C=\frac12(o-t)^2,\qquad \nabla_\theta C=(o-t)\widetilde x.$$

For repeated gradient descent on this **single fixed sample**, the prediction error follows

$$o_{k+1}-t=\left(1-\eta\|\widetilde x\|^2\right)(o_k-t).$$

Here $k$ counts parameter updates and $\|\widetilde x\|^2=(-2)^2+0.8^2+1^2=5.64$. The error decays when $0<\eta<2/5.64\approx0.3546$. This differs from the later scalar quadratic's limit because its curvature differs. Neither limit is a universal Adam setting.

**Before running:** predict which of 0.01, 0.05, 0.30 and 0.40 will approach the target monotonically, approach with oscillations, or diverge. Every curve starts from the same parameters. This is a numerical exercise on one sample, not network training.
'''

NEURON_CODE='''import numpy as np
import matplotlib.pyplot as plt

sample = np.array([x1, x2, 1.0])
initial_parameters = np.array([w1, w2, b], dtype=float)
curvature = sample @ sample
print(f"Single-sample learning-rate limit: 0 < eta < {2/curvature:.6f}")
fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
for trial_rate in [0.01, 0.05, 0.30, 0.40]:
    parameters = initial_parameters.copy()
    predictions = [parameters @ sample]
    for update in range(20):
        prediction = parameters @ sample
        parameters -= trial_rate * (prediction-t) * sample
        predictions.append(parameters @ sample)
    predictions = np.asarray(predictions)
    axes[0].plot(predictions[:7], marker=".", label=f"eta={trial_rate}")
    axes[1].semilogy(0.5*(predictions-t)**2, marker=".", label=f"eta={trial_rate}")
axes[0].axhline(t, color="black", linestyle="--", label="target")
axes[0].set(xlabel="Parameter update k", ylabel="Prediction o",
            title="Early response: updates 0-6")
axes[1].set(xlabel="Parameter update k", ylabel="Single-sample loss C",
            title="Full 20-update loss history")
for ax in axes:
    ax.legend(); ax.grid(alpha=0.2)
fig.tight_layout(); plt.show()
first_parameters = initial_parameters - 0.05*(initial_parameters @ sample-t)*sample
assert np.isclose(first_parameters @ sample, -0.23824, atol=1e-12)
print("At eta=0.05, the first prediction is", first_parameters @ sample)
'''

