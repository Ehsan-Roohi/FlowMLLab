#!/usr/bin/env python3
"""Build the article cylinder-wake figure from the frozen Week-7 CNN.

One teacher-forced window of the retained ``Re=105`` LBM case is replayed with
the frozen checkpoint in ``results/cylinder_cnn``: four observed frames
(138--141) predict frame 142, ``tU/D = 77.29``, the window used by the article.
No training, filtering, or resampling of nodal values takes place.

Panels: (a) LBM vorticity, (b) CNN vorticity, (c) signed RMS-normalized
vorticity error

    e(x) = 100 (omega_CNN - omega_LBM) / RMS(omega_LBM),

with the RMS taken over the displayed fluid nodes.  The error colour scale is
linear and spans the largest displayed |e|, so no value is clipped.

Usage::

    python qa/build_cylinder_cnn_article_figure.py
    python qa/build_cylinder_cnn_article_figure.py --output /path --tiff

The ``Re=105`` case is read from ``results/cylinder_cnn/cache`` (generated by
``qa/run_cylinder_multiscale_cnn.py --run-blind``) or from ``--case``, e.g. the
published ``cylinder_cfd_re105.npz`` asset of the ``cylinder-cfd-v1`` release.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import sys
from typing import Any

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.colors import Normalize, SymLogNorm  # noqa: E402
from matplotlib.patches import Circle  # noqa: E402
from matplotlib.ticker import FixedLocator, FuncFormatter  # noqa: E402
from matplotlib.tri import Triangulation  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from flowmllab import cylinder_cnn  # noqa: E402

RESULTS = ROOT / "results" / "cylinder_cnn"
RETAINED_RE = 105
DEVELOPMENT_RE = (60, 80, 90, 110, 120, 140)
HISTORY = 4
DIAMETER = 12.0
CENTER = (60.0, 47.5)
INFLOW = 0.05
X_WINDOW = (-1.2, 12.0)
Y_WINDOW = (-3.5, 3.5)
CACHE_NAME = "re105_nx240_ny96_d12_s22000_start15000_stride25.npz"
PUBLISHED_RE105_SHA256 = "fd6bed163b1fcb94d1157b9046db60a214841ad86d91346627fe7a5106b647ee"


def _sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _load_case(path: Path) -> dict[str, Any]:
    with np.load(path, allow_pickle=False) as archive:
        case = {key: archive[key] for key in archive.files}
    case["solid"] = np.asarray(case["solid"], dtype=bool)
    if float(case["reynolds"]) != RETAINED_RE:
        raise ValueError(f"{path} is not the Re={RETAINED_RE} case")
    if case["u"].shape[1:] != (96, 240):
        raise ValueError("unexpected LBM grid; the article figure uses 240x96")
    return case


def _model(metrics: dict[str, Any]) -> Any:
    settings = metrics["model"]
    model = cylinder_cnn.build_multiscale_predictor(
        history=HISTORY,
        filters=int(settings["filters"]),
        base=settings.get("residual_base", "persistence"),
        periodic_y=bool(settings.get("periodic_y_padding", False)),
    )
    model.load_weights(RESULTS / "multiscale_cnn.weights.h5")
    if model.count_params() != int(settings["parameters"]):
        raise AssertionError("checkpoint parameter count differs from metrics record")
    return model


def replay(case: dict[str, Any], model: Any) -> dict[str, Any]:
    """Return LBM, CNN and cubic one-step vorticity for the article window."""
    windows = cylinder_cnn.temporal_windows(case["u"].shape[0], history=HISTORY)
    display = np.arange(0, len(windows), 2)
    window = windows[int(display[len(display) // 2])]
    fluid = (~case["solid"]).astype(np.float32)[..., None]
    re_center = 0.5 * (min(DEVELOPMENT_RE) + max(DEVELOPMENT_RE))
    re_scale = 0.5 * (max(DEVELOPMENT_RE) - min(DEVELOPMENT_RE))
    re_channel = np.full_like(fluid, (RETAINED_RE - re_center) / re_scale)
    values = np.concatenate(
        [cylinder_cnn.stack_history(case, window.history), re_channel, fluid], axis=-1
    )[None]
    before = [weight.numpy().copy() for weight in model.weights]
    prediction = np.asarray(model(values, training=False))[0]
    if not all(np.array_equal(a, b.numpy()) for a, b in zip(before, model.weights)):
        raise AssertionError("inference changed the frozen weights")
    truth = np.stack([case[name][window.target] for name in ("u", "v", "p")], axis=-1)
    cubic = np.stack(
        [
            cylinder_cnn.polynomial_forecast(case[name][window.history], degree=3)
            for name in ("u", "v")
        ],
        axis=-1,
    ) * fluid
    omega = {
        name: cylinder_cnn.vorticity(field[..., 0], field[..., 1], diameter=DIAMETER)
        for name, field in (("lbm", truth), ("cnn", prediction), ("cubic", cubic))
    }
    x = (np.arange(case["solid"].shape[1], dtype=float) - CENTER[0]) / DIAMETER
    y = (np.arange(case["solid"].shape[0], dtype=float) - CENTER[1]) / DIAMETER
    ix = np.flatnonzero((x >= X_WINDOW[0]) & (x <= X_WINDOW[1]))
    iy = np.flatnonzero((y >= Y_WINDOW[0]) & (y <= Y_WINDOW[1]))
    crop = np.ix_(iy, ix)
    solid = case["solid"][crop]
    reference = omega["lbm"][crop]
    rms = float(np.sqrt(np.mean(reference[~solid] ** 2)))
    errors = {
        name: 100.0 * (omega[name][crop] - reference) / rms for name in ("cnn", "cubic")
    }
    return {
        "x": x[ix],
        "y": y[iy],
        "solid": solid,
        "reference": reference,
        "prediction": omega["cnn"][crop],
        "error_percent": errors["cnn"],
        "cubic_error_percent": errors["cubic"],
        "reference_rms": rms,
        "history": window.history.tolist(),
        "target": int(window.target),
        "dimensionless_time": float(
            case["snapshot_time"][window.target] * INFLOW / DIAMETER
        ),
    }


def render(fields: dict[str, Any], output: Path, *, dpi: int, tiff: bool) -> list[Path]:
    x, y, solid = fields["x"], fields["y"], fields["solid"]
    reference, prediction, error = (
        fields["reference"],
        fields["prediction"],
        fields["error_percent"],
    )
    fluid = ~solid
    xx, yy = np.meshgrid(x, y)
    triangulation = Triangulation(xx[fluid], yy[fluid])
    field_bound = float(max(np.abs(reference[fluid]).max(), np.abs(prediction[fluid]).max()))
    error_bound = float(np.abs(error[fluid]).max())
    error_rms = float(np.sqrt(np.mean(error[fluid] ** 2)))

    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 15,
            "axes.titlesize": 18,
            "axes.labelsize": 17,
            "xtick.labelsize": 14,
            "ytick.labelsize": 14,
            "axes.linewidth": 0.9,
            "savefig.facecolor": "white",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
        }
    )
    fig, axes = plt.subplots(3, 1, figsize=(10.4, 15.1))
    fig.subplots_adjust(left=0.105, right=0.82, bottom=0.055, top=0.955, hspace=0.24)

    field_norm = SymLogNorm(linthresh=0.2, linscale=0.6, vmin=-field_bound, vmax=field_bound)
    field_levels = np.unique(
        np.r_[-field_bound, field_norm.inverse(np.linspace(0, 1, 257)), 0.0, field_bound]
    )
    error_tick = _nice_step(error_bound)
    error_norm = Normalize(vmin=-error_bound, vmax=error_bound)
    error_levels = np.linspace(-error_bound, error_bound, 257)
    panels = (
        (reference, "(a) LBM reference", field_norm, field_levels, "RdBu_r"),
        (prediction, "(b) Frozen four-frame CNN", field_norm, field_levels, "RdBu_r"),
        (
            error,
            "(c) Signed relative error (%)",
            error_norm,
            error_levels,
            "PuOr_r",
        ),
    )
    for index, (axis, (values, title, norm, levels, cmap)) in enumerate(zip(axes, panels)):
        mappable = axis.tricontourf(
            triangulation, values[fluid], levels=levels, cmap=cmap, norm=norm, extend="neither"
        )
        mappable.set_rasterized(True)
        axis.add_patch(Circle((0.0, 0.0), 0.5, facecolor="#2b3a45", edgecolor="none", zorder=4))
        axis.set(
            xlabel=r"$(x-x_c)/D$",
            ylabel=r"$(y-y_c)/D$",
            aspect="equal",
            xticks=[0, 2, 4, 6, 8, 10, 12],
            yticks=[-3, 0, 3],
            xlim=(float(x[0]), float(x[-1])),
            ylim=(float(y[0]), float(y[-1])),
        )
        axis.set_title(title, loc="left", pad=10)
        axis.tick_params(direction="out", length=4, width=0.8)
        colorbar = fig.colorbar(mappable, ax=axis, pad=0.03, fraction=0.035, aspect=22)
        if index < 2:
            ticks = [t for t in (-10, -2, -0.5, 0, 0.5, 2, 10) if abs(t) <= field_bound]
            colorbar.set_label(r"$\omega D/U_\infty$", labelpad=8)
        else:
            top = error_tick * np.floor(error_bound / error_tick)
            ticks = list(np.arange(-top, top + 0.5 * error_tick, error_tick))
            colorbar.set_label(r"$e_\omega$ (%)", labelpad=8)
        colorbar.locator = FixedLocator(ticks)
        colorbar.formatter = FuncFormatter(
            lambda value, _: f"{value:g}".replace("-", "\N{MINUS SIGN}")
        )
        colorbar.update_ticks()
        colorbar.ax.minorticks_off()
        colorbar.ax.tick_params(labelsize=13)
        colorbar.outline.set_linewidth(0.8)

    output.mkdir(parents=True, exist_ok=True)
    written = []
    for suffix in ("png", "pdf"):
        path = output / f"fig02_wake.{suffix}"
        fig.savefig(path, dpi=dpi, bbox_inches="tight", pad_inches=0.08)
        written.append(path)
    plt.close(fig)
    # Journal production systems expect flat RGB raster artwork, not RGBA.
    from PIL import Image

    png = output / "fig02_wake.png"
    with Image.open(png) as image:
        rgb = image.convert("RGB")
    rgb.save(png, dpi=(dpi, dpi), optimize=True)
    if tiff:
        path = output / "fig02_wake.tif"
        rgb.save(path, dpi=(dpi, dpi), compression="tiff_lzw")
        written.append(path)
    return written


def _nice_step(bound: float) -> float:
    for step in (0.05, 0.1, 0.2, 0.25, 0.5, 1.0, 2.0, 2.5, 5.0, 10.0):
        if bound / step <= 4.5:
            return step
    return 20.0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--case", type=Path, default=RESULTS / "cache" / CACHE_NAME)
    parser.add_argument("--output", type=Path, default=RESULTS / "article_figure")
    parser.add_argument("--dpi", type=int, default=600)
    parser.add_argument("--tiff", action="store_true", help="also write an LZW TIFF")
    args = parser.parse_args()

    metrics = json.loads((RESULTS / "multiscale_cnn_metrics.json").read_text())
    case = _load_case(args.case)
    fields = replay(case, _model(metrics))
    written = render(fields, args.output, dpi=args.dpi, tiff=args.tiff)

    fluid = ~fields["solid"]
    error = fields["error_percent"][fluid]
    cubic = fields["cubic_error_percent"][fluid]
    record = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "reynolds": RETAINED_RE,
        "history_frames": fields["history"],
        "target_frame": fields["target"],
        "dimensionless_time": fields["dimensionless_time"],
        "case": str(args.case.name),
        "case_sha256": _sha256(args.case),
        "case_equals_published_asset": _sha256(args.case) == PUBLISHED_RE105_SHA256,
        "weights_sha256": _sha256(RESULTS / "multiscale_cnn.weights.h5"),
        "model": {
            key: metrics["model"].get(key)
            for key in ("parameters", "filters", "residual_base", "periodic_y_padding")
        },
        "window": {"x_over_D": list(X_WINDOW), "y_over_D": list(Y_WINDOW)},
        "displayed_fluid_nodes": int(fluid.sum()),
        "reference_vorticity_rms": fields["reference_rms"],
        "cnn_error_rms_percent": float(np.sqrt(np.mean(error**2))),
        "cnn_error_max_abs_percent": float(np.abs(error).max()),
        "cnn_error_p99_abs_percent": float(np.percentile(np.abs(error), 99)),
        "cubic_error_rms_percent": float(np.sqrt(np.mean(cubic**2))),
        "cubic_error_max_abs_percent": float(np.abs(cubic).max()),
        "error_definition": "100*(omega_CNN-omega_LBM)/RMS(omega_LBM) over displayed fluid nodes",
        "rendering": (
            "filled contours of unchanged native fluid nodes (piecewise-linear "
            "triangulation); exact r=D/2 circle masks the solid; vorticity on a "
            "symmetric-log scale spanning +/-max|omega|; error on a linear scale "
            "spanning +/-max|e| (no clipping)"
        ),
        "outputs": {path.name: _sha256(path) for path in written},
    }
    np.savez_compressed(
        args.output / "fig02_wake_fields.npz",
        **{key: np.asarray(value) for key, value in fields.items()},
    )
    (args.output / "fig02_wake_provenance.json").write_text(
        json.dumps(record, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
