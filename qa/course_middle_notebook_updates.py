def src(c):
    return ''.join(c['source'])

def set_source(c, text):
    text=text.strip()+'\n'
    if src(c)==text:
        return
    c['source']=text.splitlines(keepends=True)
    if c['cell_type']=='code':
        c['outputs']=[];c['execution_count']=None

def add(nb, ident, kind, text, before_last=False):
    ident='course-middle-'+ident
    cell=next((c for c in nb['cells'] if c.get('id')==ident),None)
    if cell is None:
        cell={'cell_type':kind,'id':ident,'metadata':{},'source':[]}
        if kind=='code':cell.update(outputs=[],execution_count=None)
        nb['cells'].insert(len(nb['cells'])-1 if before_last else len(nb['cells']),cell)
    set_source(cell,text)

def matched(nb, token):
    matches=[c for c in nb['cells'] if token in src(c)]
    if len(matches)!=1:
        raise ValueError(f'Expected exactly one cell containing {token!r}; found {len(matches)}')
    return matches[0]

